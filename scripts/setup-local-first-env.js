const fs = require('fs');
const os = require('os');
const path = require('path');

const envDir = path.join(os.homedir(), '.context');
const envPath = path.join(envDir, '.env');

const defaults = {
  EMBEDDING_PROVIDER: 'Ollama',
  EMBEDDING_MODEL: 'nomic-embed-text',
  OLLAMA_MODEL: 'nomic-embed-text',
  OLLAMA_HOST: 'http://127.0.0.1:11434',
  MILVUS_ADDRESS: 'localhost:19530',
  SPLITTER_TYPE: 'ast',
};

function parseEnv(content) {
  const values = new Map();
  for (const line of content.split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#') || !trimmed.includes('=')) {
      continue;
    }
    const index = trimmed.indexOf('=');
    values.set(trimmed.slice(0, index), trimmed.slice(index + 1));
  }
  return values;
}

fs.mkdirSync(envDir, { recursive: true });

const existing = fs.existsSync(envPath)
  ? parseEnv(fs.readFileSync(envPath, 'utf8'))
  : new Map();

for (const [key, value] of Object.entries(defaults)) {
  existing.set(key, value);
}

const output = [
  '# Claude Context local-first configuration',
  '# Generated by: pnpm setup:local',
  ...Array.from(existing.entries()).map(([key, value]) => `${key}=${value}`),
  '',
].join('\n');

fs.writeFileSync(envPath, output, 'utf8');

console.log(`Wrote local-first config to ${envPath}`);
console.log('Required local services:');
console.log('- Ollama running at http://127.0.0.1:11434');
console.log('- Ollama embedding model: nomic-embed-text');
console.log('- Milvus running at localhost:19530');
